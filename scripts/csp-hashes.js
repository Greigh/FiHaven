#!/usr/bin/env node
/* ═══════════════════════════════════════════════════════════
   csp-hashes.js — recompute the SHA-256 hashes of every inline
   <script> in client/*.html for the CSP allowlist.

   The CSP names inline scripts by hash instead of using
   'unsafe-inline', so EDITING ANY INLINE SCRIPT BREAKS THE PAGE
   until its hash is updated here. Run this (or `npm run generate`) —
   it rewrites INLINE_SCRIPT_HASHES in server/securityHeaders.js itself.

     node scripts/csp-hashes.js
     node scripts/csp-hashes.js --check    # exit 1 if out of date (CI)
═══════════════════════════════════════════════════════════ */

'use strict';

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

// Both directories ship HTML: client/ is Vite-processed, client/public/ is
// copied verbatim (it holds the OAuth return pages the Android sign-in flow
// lands on). Missing the second set is exactly the kind of gap that only shows
// up as a broken sign-in once the CSP is enforcing.
const HTML_DIRS = [
  path.join(__dirname, '..', 'client'),
  path.join(__dirname, '..', 'client', 'public'),
];

// Matches <script> elements with no src attribute — i.e. the inline ones.
const INLINE_SCRIPT_RE = /<script(?![^>]*\ssrc=)[^>]*>([\s\S]*?)<\/script>/g;

const SECURITY_HEADERS = path.join(__dirname, '..', 'server', 'securityHeaders.js');
const ALLOWLIST_RE = /const INLINE_SCRIPT_HASHES = \[[\s\S]*?\]\.join\(' '\);/;

function collect() {
  const found = new Map(); // hash -> Set(files)
  for (const dir of HTML_DIRS) {
    if (!fs.existsSync(dir)) continue;
    for (const file of fs.readdirSync(dir).filter((f) => f.endsWith('.html'))) {
      const html = fs.readFileSync(path.join(dir, file), 'utf8');
      let m;
      while ((m = INLINE_SCRIPT_RE.exec(html))) {
        // The hash covers the element's exact text content, byte for byte.
        const hash = crypto.createHash('sha256').update(m[1], 'utf8').digest('base64');
        if (!found.has(hash)) found.set(hash, new Set());
        found.get(hash).add(path.basename(dir) + '/' + file);
      }
    }
  }
  return found;
}

/* collect()'s Map already carries the reporting shape generate.js needs;
   the name exists so a caller does not have to know that. */
function byHash(found) {
  return found;
}

/* A well-formed element is CSP-quoted — "'sha256-…'" — because the array is
   .join(' ')ed straight into the header. A bare 'sha256-…' is malformed and
   reads as missing, which is what makes writeAllowlist self-healing. */
const HASH_ENTRY_RE = /"'sha256-([A-Za-z0-9+/=]+)'"/g;

/** The raw base64 hashes the allowlist in securityHeaders.js currently holds. */
function currentHashes() {
  const src = fs.readFileSync(SECURITY_HEADERS, 'utf8');
  const m = src.match(ALLOWLIST_RE);
  if (!m) throw new Error('INLINE_SCRIPT_HASHES array not found in server/securityHeaders.js');
  return [...m[0].matchAll(HASH_ENTRY_RE)].map((x) => x[1]);
}

/**
 * Regenerate INLINE_SCRIPT_HASHES in server/securityHeaders.js so it names
 * exactly the inline scripts the pages carry — no paste step. Returns
 * { changed, added, removed } with the raw base64 hashes.
 */
function writeAllowlist() {
  const found = collect();
  const src = fs.readFileSync(SECURITY_HEADERS, 'utf8');
  const m = src.match(ALLOWLIST_RE);
  if (!m) throw new Error('INLINE_SCRIPT_HASHES array not found in server/securityHeaders.js');
  const have = [...m[0].matchAll(HASH_ENTRY_RE)].map((x) => x[1]);
  const want = [...found.keys()];
  const added = want.filter((h) => !have.includes(h));
  const removed = have.filter((h) => !want.includes(h));
  if (!added.length && !removed.length) return { changed: false, added, removed };

  const lines = [
    "  // SHA-256 (base64) of each inline <script> element's exact bytes in",
    '  // client/*.html and client/public/*.html — regenerated by',
    '  // scripts/csp-hashes.js (or `npm run generate`); do not edit by hand.',
    '  // The comment after each hash names the file(s) carrying it. Inline',
    '  // application/ld+json blocks are non-executable, but script-src still',
    '  // governs them, so they are hashed like everything else.',
    // Each element must carry CSP's inner quotes: the array is .join(' ')ed
    // straight into the header value, which requires 'sha256-…' quoted.
    ...want.map(
      (h) => `  "'sha256-${h}'",   // ${[...found.get(h)].sort().join(', ')}`,
    ),
  ];
  fs.writeFileSync(
    SECURITY_HEADERS,
    src.replace(m[0], `const INLINE_SCRIPT_HASHES = [\n${lines.join('\n')}\n].join(' ');`),
  );
  return { changed: true, added, removed };
}

function main() {
  const found = collect();

  if (process.argv.includes('--check')) {
    const missing = [...found.keys()].filter(
      (h) => !currentHashes().includes(h)
    );
    const extra = currentHashes().filter((h) => !found.has(h));
    if (missing.length || extra.length) {
      console.error('CSP hash list is out of date.');
      for (const h of missing) {
        console.error(`  missing 'sha256-${h}'  (${[...found.get(h)].join(', ')})`);
      }
      for (const h of extra) {
        console.error(`  stale   'sha256-${h}'  (no page carries it)`);
      }
      console.error('\nRun: node scripts/csp-hashes.js');
      process.exit(1);
    }
    console.log(`CSP hash list is current (${found.size} inline scripts).`);
    return;
  }

  const { changed, added, removed } = writeAllowlist();
  if (!changed) {
    console.log(`CSP hash list already current (${found.size} inline scripts).`);
    return;
  }
  console.log(`Updated INLINE_SCRIPT_HASHES in ${path.relative(process.cwd(), SECURITY_HEADERS)}:`);
  for (const h of added) console.log(`  + sha256-${h}  (${[...found.get(h)].join(', ')})`);
  for (const h of removed) console.log(`  - sha256-${h}`);
}

if (require.main === module) main();

module.exports = { collect, byHash, writeAllowlist, currentHashes };
