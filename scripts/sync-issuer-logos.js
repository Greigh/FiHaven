#!/usr/bin/env node
/* ═══════════════════════════════════════════════════════════
   sync-issuer-logos.js — port the web issuer brand marks to native.

   Reads client/js/issuerLogos.js (the canonical table) and regenerates:
     ios/FiHavenCore/Sources/FiHavenCore/Logic/IssuerLogos.swift
     android/core/src/main/kotlin/app/fihaven/core/logic/IssuerLogos.kt

   The SVG path `d` strings are copied verbatim (a grid 24 units tall, the
   viewBox width carried alongside); every color becomes a packed 0xRRGGBB
   integer so neither native side needs a hex parser. Run this after editing
   ISSUER_LOGO_PATHS, then commit the generated files.

   Usage: node scripts/sync-issuer-logos.js [--check]
     --check  exit 1 if the generated files are stale (no writes)
═══════════════════════════════════════════════════════════ */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SOURCE = path.join(ROOT, 'client/js/issuerLogos.js');
const SWIFT_OUT = path.join(ROOT, 'ios/FiHavenCore/Sources/FiHavenCore/Logic/IssuerLogos.swift');
const KOTLIN_OUT = path.join(ROOT, 'android/core/src/main/kotlin/app/fihaven/core/logic/IssuerLogos.kt');

const HEX_RE = /^#[0-9A-Fa-f]{6}$/;

/**
 * Read ISSUER_LOGO_PATHS out of the web source. The table spans several lines
 * per entry now, so rather than matching lines we lift the object literal and
 * evaluate it — the repo owns the file, and a format drift throws here instead
 * of silently dropping issuers.
 */
function readEntries() {
  const src = fs.readFileSync(SOURCE, 'utf8');
  const start = src.indexOf('ISSUER_LOGO_PATHS = {');
  const end = src.indexOf('\n};', start);
  if (start < 0 || end < 0) {
    throw new Error(`Could not find ISSUER_LOGO_PATHS in ${SOURCE} — has the table format changed?`);
  }
  const literal = src.slice(src.indexOf('{', start), end + 2);
  const table = new Function(`return ${literal}`)();

  const entries = Object.entries(table).map(([key, value]) => {
    if (!/^[a-z0-9]+$/.test(key)) throw new Error(`${key}: keys must be lowercase alphanumeric`);
    if (!HEX_RE.test(value.c || '')) throw new Error(`${key}: brand color must be #RRGGBB`);
    // A mark is either monochrome (`d`) or full color (`l`), never both.
    const fullColor = !!value.l;
    if (fullColor === !!value.d) throw new Error(`${key}: needs exactly one of \`d\` or \`l\``);
    const layers = fullColor ? value.l : [[value.c, value.d]];
    for (const layer of layers) {
      if (!Array.isArray(layer) || layer.length !== 2) throw new Error(`${key}: layers are [fill, d] pairs`);
      if (!HEX_RE.test(layer[0])) throw new Error(`${key}: layer fill ${layer[0]} must be #RRGGBB`);
      if (!layer[1] || layer[1].includes('"')) throw new Error(`${key}: bad path data`);
    }
    // Marks are authored 24 tall; only the width varies.
    const width = value.w == null ? 24 : Number(value.w);
    if (!(width > 0)) throw new Error(`${key}: \`w\` must be a positive number`);
    return {
      key,
      color: value.c.slice(1).toUpperCase(),
      width,
      fullColor,
      layers: layers.map(([f, d]) => ({ color: f.slice(1).toUpperCase(), d })),
    };
  });

  if (!entries.length) throw new Error(`No issuer logo entries parsed from ${SOURCE}`);
  return entries;
}

const BANNER = (tool) => `// Generated by scripts/${tool} from client/js/issuerLogos.js — do not edit by hand.`;

const DOC = [
  'Brand marks for credit-card issuers, authored 24 units tall. Brand names',
  'and logos remain trademarks of their owners and are used here only to',
  "identify a user's own cards.",
  '',
  'A monochrome mark (Simple Icons, CC0) has one recolorable layer, so it',
  'renders white on a brand-colored chip. A full-color mark (Wikimedia',
  'Commons, public domain) has several layers painted in order and keeps its',
  'own colors, so it needs a light plate instead — see `isFullColor`.',
  '',
  'Keyed by the same normalized issuer name web `issuerLogos.js` uses.',
];

function swiftSource(entries) {
  const rows = entries
    .map((e) => {
      const layers = e.layers
        .map((l) => `            IssuerLogoLayer(color: 0x${l.color}, path: "${l.d}"),`)
        .join('\n');
      return (
        `        "${e.key}": IssuerLogo(\n` +
        `            key: "${e.key}", color: 0x${e.color}, width: ${e.width}, isFullColor: ${e.fullColor},\n` +
        `            layers: [\n${layers}\n            ]\n` +
        `        ),`
      );
    })
    .join('\n');
  return `${BANNER('sync-issuer-logos.js')}
import Foundation

/// One filled shape of a brand mark.
public struct IssuerLogoLayer: Equatable, Sendable {
    /// Fill packed as 0xRRGGBB.
    public let color: UInt32
    /// SVG path \`d\` data, on a grid 24 units tall.
    public let path: String

    public init(color: UInt32, path: String) {
        self.color = color
        self.path = path
    }
}

/// A brand mark: layers painted in order on a \`width\` x 24 viewBox.
public struct IssuerLogo: Equatable, Sendable {
    /// Normalized issuer key (e.g. \`americanexpress\`).
    public let key: String
    /// Brand color packed as 0xRRGGBB.
    public let color: UInt32
    /// viewBox width; the height is always 24.
    public let width: Double
    /// Whether the mark carries its own colors and must not be recolored.
    /// Monochrome marks are tinted white on a brand chip; full-color ones
    /// get a light plate.
    public let isFullColor: Bool
    /// Layers, painted back to front. A monochrome mark has exactly one.
    public let layers: [IssuerLogoLayer]

    /// Width / height, for laying the mark out before it is drawn.
    public var aspect: Double { width / 24 }

    public init(key: String, color: UInt32, width: Double, isFullColor: Bool, layers: [IssuerLogoLayer]) {
        self.key = key
        self.color = color
        self.width = width
        self.isFullColor = isFullColor
        self.layers = layers
    }
}

${DOC.map((l) => (l ? `/// ${l}` : '///')).join('\n')}
public enum IssuerLogos {
    public static let all: [String: IssuerLogo] = [
${rows}
    ]

    /// Keys longest-first, so substring matching prefers the specific name.
    public static let keysByLength: [String] = all.keys.sorted { $0.count > $1.count }

    public static func logo(_ key: String) -> IssuerLogo? { all[key] }
}
`;
}

function kotlinSource(entries) {
  const rows = entries
    .map((e) => {
      const layers = e.layers
        .map((l) => `                IssuerLogoLayer(0x${l.color}, "${l.d}"),`)
        .join('\n');
      return (
        `        "${e.key}" to IssuerLogo(\n` +
        `            "${e.key}", 0x${e.color}, ${e.width}f, ${e.fullColor},\n` +
        `            listOf(\n${layers}\n            ),\n` +
        `        ),`
      );
    })
    .join('\n');
  return `${BANNER('sync-issuer-logos.js')}
package app.fihaven.core.logic

/**
 * One filled shape of a brand mark.
 *
 * @property color fill packed as 0xRRGGBB
 * @property path SVG path \`d\` data, on a grid 24 units tall
 */
data class IssuerLogoLayer(val color: Int, val path: String)

/**
 * A brand mark: layers painted in order on a [width] x 24 viewBox.
 *
 * @property key normalized issuer key (e.g. \`americanexpress\`)
 * @property color brand color packed as 0xRRGGBB
 * @property width viewBox width; the height is always 24
 * @property isFullColor whether the mark carries its own colors and must not
 *   be recolored. Monochrome marks are tinted white on a brand chip;
 *   full-color ones get a light plate.
 * @property layers painted back to front; a monochrome mark has exactly one
 */
data class IssuerLogo(
    val key: String,
    val color: Int,
    val width: Float,
    val isFullColor: Boolean,
    val layers: List<IssuerLogoLayer>,
) {
    /** Width / height, for laying the mark out before it is drawn. */
    val aspect: Float get() = width / 24f
}

/**
${DOC.map((l) => (l ? ` * ${l}` : ' *')).join('\n')}
 */
object IssuerLogos {
    val all: Map<String, IssuerLogo> = mapOf(
${rows}
    )

    /** Keys longest-first, so substring matching prefers the specific name. */
    val keysByLength: List<String> = all.keys.sortedByDescending { it.length }

    fun logo(key: String): IssuerLogo? = all[key]
}
`;
}

function main() {
  const check = process.argv.includes('--check');
  const entries = readEntries();
  const outputs = [
    [SWIFT_OUT, swiftSource(entries)],
    [KOTLIN_OUT, kotlinSource(entries)],
  ];

  let stale = 0;
  for (const [file, contents] of outputs) {
    const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
    if (current === contents) continue;
    stale += 1;
    if (check) {
      console.error(`stale: ${path.relative(ROOT, file)}`);
      continue;
    }
    fs.writeFileSync(file, contents);
    console.log(`wrote ${path.relative(ROOT, file)}`);
  }

  if (check) {
    if (stale) {
      console.error('Run `node scripts/sync-issuer-logos.js` and commit the result.');
      process.exit(1);
    }
    console.log(`issuer logos in sync (${entries.length} marks)`);
    return;
  }
  console.log(`${entries.length} issuer marks synced`);
}

main();
